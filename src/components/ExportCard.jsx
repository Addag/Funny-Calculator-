import React, { useState } from 'react';
import { FileText, Check, Copy, X, Share2 } from 'lucide-react';

export default function ExportCard({
  expression,
  result,
  confidence,
  absurdUnit,
  proof,
  modeName,
  onClose
}) {
  const [copied, setCopied] = useState(false);

  const proofText = proof && proof.length > 0
    ? proof.map((step, idx) => `  ${idx + 1}. ${step}`).join('\n')
    : '  1. Consulted internal vibes.\n  2. Accepted the outcome without question.';

  const formattedReport = `========================================
🎓 OFFICIAL MATHEMATICAL SUBMISSION
Mode: ${modeName || 'Wrong Answers Only'}
========================================
Problem:          ${expression || result}
Reported Result:  ${result}
AI Confidence:    ${confidence || '100% Unearned'}
${absurdUnit ? `Scientific Scale: ${absurdUnit}\n` : ''}
Step-by-Step Formal Proof:
${proofText}

Conclusion:
This answer is mathematically questionable, socially
unacceptable, but legally binding.
========================================
Generated by "Wrong Answers Only" Calculator`;

  const handleCopy = () => {
    navigator.clipboard.writeText(formattedReport);
    setCopied(true);
    setTimeout(() => setCopied(false), 2200);
  };

  return (
    <div className="captcha-overlay">
      <div className="export-card">
        <div className="export-header">
          <div className="export-title">
            <FileText size={20} color="var(--accent-cyan)" />
            <span>Homework / Spreadsheet Export</span>
          </div>
          <button className="proof-close-btn" onClick={onClose} title="Close">
            <X size={16} />
          </button>
        </div>

        <p className="export-subtitle">
          Copy this formatted receipt to paste into your group project, homework, or email to your accountant:
        </p>

        <pre className="export-pre">
          {formattedReport}
        </pre>

        <div className="export-actions">
          <button className="export-copy-btn" onClick={handleCopy}>
            {copied ? (
              <>
                <Check size={16} color="#000" />
                <span>Copied to Clipboard! 📋</span>
              </>
            ) : (
              <>
                <Copy size={16} />
                <span>Copy to Homework / Clipboard</span>
              </>
            )}
          </button>
        </div>
      </div>
    </div>
  );
}
